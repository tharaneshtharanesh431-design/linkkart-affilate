package com.kart.controller;

import com.kart.dto.ApiResponse;
import com.kart.dto.link.AffiliateLinkRequest;
import com.kart.dto.link.AffiliateLinkResponse;
import com.kart.service.AffiliateLinkService;
import io.swagger.v3.oas.annotations.Operation;
import io.swagger.v3.oas.annotations.tags.Tag;
import jakarta.validation.Valid;
import lombok.RequiredArgsConstructor;
import org.springframework.http.ResponseEntity;
import org.springframework.web.bind.annotation.*;

import java.util.List;

@RestController
@RequestMapping("/api/affiliate-links")
@RequiredArgsConstructor
@Tag(name = "Affiliate Links")
public class AffiliateLinkController {

    private final AffiliateLinkService affiliateLinkService;

    @PostMapping
    @Operation(summary = "Generate a new tracking link for a product")
    public ResponseEntity<ApiResponse<AffiliateLinkResponse>> generateLink(@Valid @RequestBody AffiliateLinkRequest request) {
        AffiliateLinkResponse response = affiliateLinkService.generateLink(request);
        return ResponseEntity.ok(ApiResponse.success("Affiliate link generated successfully", response));
    }

    @GetMapping
    @Operation(summary = "Get all tracking links generated by the logged-in affiliate")
    public ResponseEntity<ApiResponse<List<AffiliateLinkResponse>>> getMyLinks() {
        List<AffiliateLinkResponse> response = affiliateLinkService.getMyLinks();
        return ResponseEntity.ok(ApiResponse.success("Affiliate links retrieved successfully", response));
    }
}
